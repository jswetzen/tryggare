import { describe, expect, it } from 'vitest';
import fixture from './__fixtures__/form-spec.v1.json';
import type { RegistrationFormSpec } from '$lib/api/types';

// JSON imports widen literals ('parent' -> string), so compare against the
// type with literals widened; missing or retyped keys still fail the check.
type Widen<T> = T extends string
  ? string
  : T extends number
    ? number
    : T extends (infer U)[]
      ? Widen<U>[]
      : T extends object
        ? { [K in keyof T]: Widen<T[K]> }
        : T;

// Reverse direction: every key in the fixture must exist on the type. A
// failure shows up as a type error in `npm run check` (svelte-check), not at
// vitest runtime.
type NoExtraKeys<Fixture, Spec> = [Exclude<keyof Fixture, keyof Spec>] extends [never]
  ? true
  : never;
const topLevel: NoExtraKeys<typeof fixture, RegistrationFormSpec> = true;
const ticketType: NoExtraKeys<
  (typeof fixture.ticket_types)[number],
  RegistrationFormSpec['ticket_types'][number]
> = true;
const extra: NoExtraKeys<
  (typeof fixture.extras)[number],
  RegistrationFormSpec['extras'][number]
> = true;
const session: NoExtraKeys<
  (typeof fixture.sessions)[number],
  RegistrationFormSpec['sessions'][number]
> = true;
const field: NoExtraKeys<
  (typeof fixture.fields.parent)[number],
  RegistrationFormSpec['fields']['parent'][number]
> = true;

// Fixture is generated by the backend (registrations/tests_form_spec.py).
describe('form spec contract', () => {
  it('fixture satisfies RegistrationFormSpec', () => {
    const spec = fixture satisfies Widen<RegistrationFormSpec>;
    expect([topLevel, ticketType, extra, session, field]).toEqual(Array(5).fill(true));
    expect(spec.spec_version).toBe(1);
    expect(spec.fields.parent.map((f) => f.key)).toContain('phone');
  });
});
